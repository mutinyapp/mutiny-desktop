export type ColorRole = keyof typeof colorModes.dark.normal;
export type Scheme = keyof typeof colorModes;

export function color(role: ColorRole, scheme: Scheme = "dark", highContrast = false): string {
  const mode = colorModes[scheme];
  if (!mode || !Object.hasOwn(mode.normal, role)) throw new Error(`Unknown color role/scheme: ${scheme}.${role}`);
  return (highContrast ? mode.highContrast : mode.normal)[role];
}
